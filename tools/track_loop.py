"""The geometry of a tracked vehicle's belts: each belt's loop, its link pitch, and the generated Rust table.

Pure numpy (no bpy), so it runs and is tested outside Blender; `split_moving_parts.py --model carrier
--track-out <rs>` feeds it the belt faces it cuts from the scan.

    python3 -m unittest tools/test_track_loop.py -v

The side plane is (z, y) in the glTF frame: z forward (the carrier faces +Z), y up.
"""

import numpy as np

FIT_PASSES = 6  # passes of centring the loop on the faces nearest it
MIN_PITCH = 0.004  # shorter repeats are surface detail on a link, not links
PITCH_BIN = 0.0002  # histogram bin for the density of faces along the run


def fit_loop(belt_zy, step, span=None, weights=None):
    """The belt's mid-line from its faces' centroids (z, y): a closed polyline (last point is not the first)
    sampled every ~`step`, running the way the belt travels when the vehicle drives forward: the lower run
    front to back (toward -z), up round the back, the upper run back to front, down round the front.
    It starts under the loop's middle.

    A principal curve: start from the convex hull, then move each point along its normal by the mean
    offset of the faces nearest the loop within `span` of it (default three steps; make it a whole number
    of link pitches on a real belt, or the curve follows each link's teeth and pads), and resample, until it
    settles in the middle of the band. Averaging offsets rather than positions keeps arcs from shrinking.
    `weights` (the faces' areas) make it the middle of the surface, however finely each part is meshed."""
    points = np.asarray(belt_zy, dtype=float)
    weights = np.ones(len(points)) if weights is None else np.asarray(weights, dtype=float)
    reach = max(1, int(round((span or 3 * step) / step / 2)))
    loop = resample(convex_hull(points), step)
    for _ in range(FIT_PASSES):
        loop = resample(centre_on(points, weights, loop, reach), step)
    return start_and_direction(loop)


def link_pitch(lower_run_z):
    """The links' repeat distance along a straight run, from the z of the faces (or vertices) on it.

    Give it faces whose density repeats once per link, such as the run's ground faces: all of a belt's faces
    can repeat twice per link (the carrier's do: connector and horn edges), and the first strong repeat wins.
    Autocorrelates the faces' density along z; the first strong peak gives the pitch roughly, and the
    peak at the largest whole multiple of it within half the run refines it."""
    z = np.asarray(lower_run_z, dtype=float)
    counts, _ = np.histogram(z, bins=np.arange(z.min(), z.max() + PITCH_BIN, PITCH_BIN))
    density = counts - counts.mean()
    overlap = np.arange(len(density), 0, -1)
    correlation = np.correlate(density, density, "full")[len(density) - 1 :] / overlap

    first, last = int(np.ceil(MIN_PITCH / PITCH_BIN)), len(density) // 2
    window = correlation[first:last]
    peaks = [i for i in range(1, len(window) - 1) if window[i - 1] < window[i] >= window[i + 1]]
    strong = [i for i in peaks if window[i] >= 0.5 * window.max()]
    if not strong:
        raise ValueError("no repeat found along the run")
    rough = (first + strong[0]) * PITCH_BIN

    multiple = max(1, int(last * PITCH_BIN / rough))
    around = int(round(multiple * rough / PITCH_BIN))
    reach = max(1, int(rough / PITCH_BIN / 4))
    lag = around - reach + int(np.argmax(correlation[around - reach : around + reach + 1]))
    return refine_peak(correlation, lag) * PITCH_BIN / multiple


def rust_track_module(loops, xs, links):
    """The text of `src/player/vehicle/carrier_track.rs`: loops (z, y) and x per side, left (+X) first."""
    sides = "".join(
        "    &[\n" + "".join(f"        [{number(z)}, {number(y)}],\n" for z, y in loop) + "    ],\n" for loop in loops
    )
    return (
        "//! Generated by `tools/split_moving_parts.py --model carrier --track-out …`; regenerate, don't hand-edit.\n"
        "\n"
        "/// Each track's belt mid-line (z, y), closed, in the order the belt runs when the carrier drives forward.\n"
        f"pub(super) const TRACK_LOOPS: [&[[f32; 2]]; {len(loops)}] = [\n{sides}];\n"
        "/// Each track's mid-plane x.\n"
        f"pub(super) const TRACK_X: [f32; {len(xs)}] = [{', '.join(number(x) for x in xs)}];\n"
        "/// Links round each track: the integer nearest loop length / scanned pitch.\n"
        f"pub(super) const TRACK_LINKS: [usize; {len(links)}] = [{', '.join(str(int(n)) for n in links)}];\n"
    )


def loop_length(loop):
    return float(np.linalg.norm(np.roll(loop, -1, axis=0) - loop, axis=1).sum())


# ---- helpers ----


def number(value):
    return f"{float(value) + 0.0:.6f}"  # + 0.0 turns -0.0 into 0.0


def convex_hull(points):
    """Andrew's monotone chain, counter-clockwise, on the distinct points."""
    unique = np.unique(np.round(points, 6), axis=0)  # sorted by z, then y

    def chain(ordered):
        hull = []
        for p in ordered:
            while len(hull) >= 2 and cross(hull[-2], hull[-1], p) <= 0:
                hull.pop()
            hull.append(tuple(p))
        return hull[:-1]

    return np.array(chain(unique) + chain(unique[::-1]))


def cross(o, a, b):
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def resample(loop, step):
    """The closed polyline resampled at an equal spacing as near `step` as divides its length."""
    closed = np.vstack([loop, loop[:1]])
    along = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(closed, axis=0), axis=1))])
    count = max(3, int(round(along[-1] / step)))
    at = np.arange(count) * along[-1] / count
    return np.stack([np.interp(at, along, closed[:, 0]), np.interp(at, along, closed[:, 1])], axis=1)


def nearest(points, loop, chunk=20000):
    """The index of the loop point nearest each point."""
    return np.concatenate([
        np.argmin(((points[i : i + chunk, None, :] - loop[None, :, :]) ** 2).sum(axis=2), axis=1)
        for i in range(0, len(points), chunk)
    ])


def centre_on(points, weights, loop, reach):
    """Move each loop point along its normal by the weighted mean offset of the points nearest the loop
    within `reach` points of it, each offset measured from the loop point it is nearest."""
    owner = nearest(points, loop)
    normals = normals_of(loop)
    offsets = ((points - loop[owner]) * normals[owner]).sum(axis=1)
    window = np.ones(2 * reach + 1)
    count = circular_sum(np.bincount(owner, weights, minlength=len(loop)), window)
    total = circular_sum(np.bincount(owner, weights * offsets, minlength=len(loop)), window)
    shift = np.divide(total, count, out=np.zeros(len(loop)), where=count > 0)
    return loop + normals * shift[:, None]


def normals_of(loop):
    """Unit normals, turned a quarter left of the direction the loop runs."""
    tangents = np.roll(loop, -1, axis=0) - np.roll(loop, 1, axis=0)
    tangents /= np.linalg.norm(tangents, axis=1, keepdims=True)
    return np.stack([-tangents[:, 1], tangents[:, 0]], axis=1)


def circular_sum(values, window):
    reach = len(window) // 2
    padded = np.concatenate([values[-reach:], values, values[:reach]])
    return np.convolve(padded, window, "valid")


def start_and_direction(loop):
    """Order the loop clockwise in (z right, y up), so the lower run goes toward -z, from under its middle."""
    area = np.sum(loop[:, 0] * np.roll(loop[:, 1], -1) - np.roll(loop[:, 0], -1) * loop[:, 1])
    if area > 0:  # counter-clockwise
        loop = loop[::-1]
    below = loop[:, 1] < loop[:, 1].mean()
    start = np.flatnonzero(below)[np.argmin(np.abs(loop[below, 0] - loop[:, 0].mean()))]
    return np.roll(loop, -start, axis=0)


def refine_peak(values, index):
    """The sub-sample position of the peak at `index`, from a parabola through it and its neighbours."""
    if index <= 0 or index >= len(values) - 1:
        return float(index)
    left, centre, right = values[index - 1], values[index], values[index + 1]
    bend = left - 2 * centre + right
    return float(index) if bend == 0 else index + 0.5 * (left - right) / bend


def place_on(points, loop):
    """Each point's arc length along the loop (of the loop point it is nearest, plus its run past it)
    and its offset from the loop, positive outward (the loop runs clockwise, as `fit_loop` orders it)."""
    points = np.asarray(points, dtype=float)
    owner = nearest(points, loop)
    normals = normals_of(loop)
    tangents = np.stack([normals[:, 1], -normals[:, 0]], axis=1)
    relative = points - loop[owner]
    along = owner * loop_length(loop) / len(loop) + (relative * tangents[owner]).sum(axis=1)
    return along, (relative * normals[owner]).sum(axis=1)
