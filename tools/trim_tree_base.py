"""Trim a Tripo model's ground slab and measure its collision pillars.

Models may contain multiple mesh objects. They are joined before trimming and
collision sampling. Everything below `cut` (a fraction of model height) is
removed and the model is lowered so the cut sits at y = 0.

  blender -b --python tools/trim_tree_base.py -- raw.glb out.glb <cut> src/world/pillars/<name>.rs
  npx @gltf-transform/cli@4 resize out.glb assets/models/trees/<name>.glb --width 1024 --height 1024

Raw models may first be decimated with gltf-transform when needed.
To re-measure an installed (already trimmed) stand without touching it:
  blender -b --python tools/trim_tree_base.py -- assets/models/trees/<name>.glb - 0 src/world/pillars/<name>.rs

The pillars file is a Rust array of `Pillar`s (glTF axes, model units): the
stand's surface sampled into vertical columns on a PILLAR_CELL grid, each
spanning the lowest to highest geometry in its column. src/world/trees.rs
includes it for collision and for grounding the stand.
Pass --split-columns after the output path to preserve gaps under roofs.
"""
import bpy, bmesh, math, sys

SRC, DST, CUT, PILLARS = sys.argv[sys.argv.index('--') + 1:][:4]
SPLIT_COLUMNS = "--split-columns" in sys.argv[sys.argv.index('--') + 5:]
CUT = float(CUT)
PILLAR_CELL = 0.03
# Columns whose geometry never rises above this (model units) are only litter.
MIN_TOP = 0.025

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=SRC)
meshes = [o for o in bpy.context.scene.objects if o.type == 'MESH']
mesh = meshes[0]
if len(meshes) > 1:
    bpy.ops.object.select_all(action='DESELECT')
    for obj in meshes:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = mesh
    bpy.ops.object.join()
bpy.context.view_layer.objects.active = mesh
mesh.select_set(True)
bpy.ops.object.parent_clear(type='CLEAR_KEEP_TRANSFORM')
bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
for o in list(bpy.context.scene.objects):
    if o is not mesh:
        bpy.data.objects.remove(o)

bm = bmesh.new()
bm.from_mesh(mesh.data)
height = max(v.co.z for v in bm.verts)
z_cut = CUT * height
geom = bm.verts[:] + bm.edges[:] + bm.faces[:]
if CUT > 0:
    bmesh.ops.bisect_plane(bm, geom=geom, plane_co=(0, 0, z_cut), plane_no=(0, 0, 1), clear_inner=True)

# Drop islands left floating below the trunks' reach (pebbles, slab crumbs).
bm.verts.ensure_lookup_table()
seen, small = set(), []
for start in bm.verts:
    if start in seen:
        continue
    island, stack = [], [start]
    seen.add(start)
    while stack:
        v = stack.pop()
        island.append(v)
        for e in v.link_edges:
            w = e.other_vert(v)
            if w not in seen:
                seen.add(w)
                stack.append(w)
    if max(v.co.z for v in island) - z_cut < 0.03 * height:
        small.extend(island)
bmesh.ops.delete(bm, geom=small, context='VERTS')

for v in bm.verts:
    v.co.z -= z_cut

# Collision pillars: sample every triangle densely, bin samples into columns.
columns = {}
samples = {}
bm.faces.ensure_lookup_table()
for face in bm.faces:
    corners = [v.co for v in face.verts]
    for a, b, c in ((corners[0], corners[i], corners[i + 1]) for i in range(1, len(corners) - 1)):
        steps = max(1, math.ceil(max((b - a).length, (c - a).length, (c - b).length) / (PILLAR_CELL / 2)))
        for i in range(steps + 1):
            for j in range(steps + 1 - i):
                p = a + (b - a) * (i / steps) + (c - a) * (j / steps)
                key = (round(p.x / PILLAR_CELL), round(p.y / PILLAR_CELL))
                lo, hi, n = columns.get(key, (p.z, p.z, 0))
                columns[key] = (min(lo, p.z), max(hi, p.z), n + 1)
                if SPLIT_COLUMNS:
                    samples.setdefault(key, []).append(p.z)


def intervals(key, lo, hi):
    if not SPLIT_COLUMNS:
        yield lo, hi
        return
    heights = sorted(samples[key])
    start = end = heights[0]
    for height in heights[1:]:
        if height - end > 2 * PILLAR_CELL:
            yield start, end
            start = height
        end = height
    yield start, end


pillars = [
    (kx * PILLAR_CELL, -ky * PILLAR_CELL, start, end)  # Blender (x, y) is glTF (x, -z).
    for (kx, ky), (lo, hi, n) in sorted(columns.items())
    if n >= 3
    for start, end in intervals((kx, ky), lo, hi)
    if end >= MIN_TOP
]

bm.to_mesh(mesh.data)
bm.free()
if DST != '-':
    bpy.ops.export_scene.gltf(filepath=DST, export_format='GLB', export_image_format='AUTO')

radius = 0.6 * PILLAR_CELL
with open(PILLARS, 'w') as out:
    out.write(f'// Generated by tools/trim_tree_base.py from {SRC.split("/")[-1]}; do not edit.\n&[\n')
    for x, z, lo, hi in pillars:
        out.write(f'    Pillar {{ x: {x:.3f}, z: {z:.3f}, radius: {radius:.3f}, bottom: {lo:.3f}, top: {hi:.3f} }},\n')
    out.write(']\n')
print(f'HEIGHT {height - z_cut:.4f} PILLARS {len(pillars)}')
